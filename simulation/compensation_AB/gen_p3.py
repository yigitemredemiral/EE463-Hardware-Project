"""Paket 3 - compensation A/B comparison (transient bonus).
Base: LTspice_RevF1/RevF1_G_fra90_20V.cir (config G, VDMOS MOSFET models) with the final RevF1 values
RFREQ 24.3k and RGH 4.7 ohm. MOSFET model detail does not matter for the loop study; the official Infineon
library is not in the package. Usage: python gen_p3.py prime|main|steps   (generates and runs)."""
import os, sys, subprocess, time
from concurrent.futures import ThreadPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, '..', 'ltspice_RevF1_runs', 'RevF1_G_fra90_20V.cir')
LT = r'C:\Program Files\ADI\LTspice\LTspice.exe'
COMP = {'A': '27n Rser=8.2K Cpar=470p', 'B': '68n Rser=3.9K Cpar=1n'}
LOOP_OLD = '@LOOP OUT FBOUT fstart=500 fend=50000 oct=2 delay=3m pp0=40m pp1=15m f0=2k f1=10k tsettle=1m tavgmin=1m nmax=1'
LOOP_PRIME = '@LOOP OUT FBOUT fstart=500 fend=16k oct=1 delay=6m pp0=50m pp1=50m f0=1k f1=2k tsettle=1m tavgmin=2m nmax=1'
LOOP_FRA = '@LOOP OUT FBOUT fstart=250 fend=32000 oct=3 delay=2m pp0=40m pp1=15m f0=2k f1=10k tsettle=1m tavgmin=1m nmax=1'
RLOAD_OLD = 'Rload OUT 0 R={if(TEST==1,table(time,0,RL,7m,RL,7.01m,RFAULT,10m,RFAULT,10.01m,RL),RL)}'

def make(name, comp, vin, tail, rl=2.4, loop=LOOP_PRIME, rload=None, vsrc=None, css=None):
    s = open(BASE, encoding='latin-1').read()
    def rep(a, b):
        nonlocal s
        assert a in s, a
        s = s.replace(a, b)
    rep('R3 N004 0 24.9k', 'R3 N004 0 24.3k')
    rep('RgH TG GHI 6.8', 'RgH TG GHI 4.7')
    rep('C4 N008 0 27n Rser=8.2K Cpar=470p', 'C4 N008 0 ' + COMP[comp])
    rep('.param VIN=20 RL=1.6', f'.param VIN={vin} RL={rl}')
    rep('.lib models' + chr(92), '.lib ../ltspice_RevF1_runs/models/')
    rep('.lib models/', '.lib ../ltspice_RevF1_runs/models/')
    rep(LOOP_OLD, loop)
    if rload: rep(RLOAD_OLD, rload)
    if vsrc: rep('V1 SOURCE 0 {VIN}', vsrc)
    if css: rep('C5 N007 0 100n', 'C5 N007 0 ' + css)
    rep('V(N008)', 'V(N008) V(FBOUT)')
    rep('* RevF1 generated by gen.py', '* Paket 3 comp ' + comp + ' generated by gen_p3.py')
    rep('.fra loadstate="RevF1_G_prime27_20V.state"', tail)
    open(os.path.join(HERE, name + '.cir'), 'w', encoding='latin-1', newline='\r\n').write(s)
    return name

def ok(name):
    p = os.path.join(HERE, name + '.log')
    if not os.path.exists(p): return False
    t = open(p, 'rb').read().decode('latin-1', 'ignore')
    return 'Total elapsed time' in t and 'aborted' not in t.lower() and 'simulation failed' not in t.lower()

def run1(name):
    t0 = time.time(); subprocess.run([LT, '-b', name + '.cir'], cwd=HERE)
    return name, 'ok' if ok(name) else 'FAILED', time.time() - t0

names = []
stage = sys.argv[1]
st = lambda c, v: f'P3_{c}_prime_{v}V.state'
if stage == 'prime':
    for c in 'AB':
        for v in (20, 48):
            names.append(make(f'P3_{c}_prime_{v}V', c, v, f'.options method=gear\n.tran 0 8m 0 100n\n.savestate "{st(c, v)}"', css='22n'))
else:
    for c in 'AB':
        for v in (20, 48):
            if stage != 'steps': names.append(make(f'P3_{c}_fra_{v}V', c, v, f'.fra loadstate="{st(c, v)}"', loop=LOOP_FRA))
            # .loadstate continues the time axis from the prime (8 ms): load step 5 A -> 2.5 A at 9 ms, back to 5 A at 13 ms (10 us edges)
            names.append(make(f'P3_{c}_load_{v}V', c, v, f'.loadstate "{st(c, v)}"\n.tran 0 17m 0 100n',
                rload='Rload OUT 0 R={table(time,0,RL,9m,RL,9.01m,2*RL,13m,2*RL,13.01m,RL)}'))
        # line step 20 V -> 30 V at 9 ms (100 us edge), back at 13 ms
        names.append(make(f'P3_{c}_line_20V', c, 20, f'.loadstate "{st(c, 20)}"\n.tran 0 18m 0 100n',
            vsrc='V1 SOURCE 0 PWL(0 20 9m 20 9.1m 30 13m 30 13.1m 20)'))
with ThreadPoolExecutor(10) as ex:
    for r in ex.map(run1, names): print(f'{r[0]:24s} {r[1]:7s} {r[2]:6.0f}s', flush=True)
