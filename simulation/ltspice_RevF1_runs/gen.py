"""RevF1 netlist generator. Base = RevD5E1_24V_60W.cir (Yasin, unchanged copy as base_*.txt).
Every change vs base is applied by explicit string replacement and asserted."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
BASE = open(os.path.join(HERE, 'base_RevD5E1_24V_60W.cir.txt'), encoding='latin-1').read()
BASE = BASE.replace('\r\n', '\n')
for _l in ['.temp 27\n', '.loadstate "RevD5E1_prime27.state"\n', '.tran 0 14m 0 100n\n']:
    assert BASE.count(_l) == 1, _l
    BASE = BASE.replace(_l, '')

BSC040 = ('.model BSC040N08NS5 VDMOS(Rg=1.1 Vto=3.0 Rd=31u Rs=634u Rb=2.11m Kp=40.6 Lambda=0.03 '
          'Cgdmin=17p Cgdmax=0.685n A=0.2 Cgs=2.84n Cjo=0.81n M=0.75 Is=28.7p VJ=2.5 N=1.12 TT=15n '
          'ksubthres=.1 mfg=Infineon_scaled_from_BSC026 Vds=80 Ron=4.0m Qg=43n)')

VARIANTS = {  # name: (RFREQ, RGH, Q1 model)
    'a': ('30.1k', '4.7', 'BSC026N08NS5'),
    'b': ('24.3k', '4.7', 'BSC026N08NS5'),
    'c': ('24.3k', '4.7', 'BSC040N08NS5'),
    'd': ('24.3k', '3.3', 'BSC040N08NS5'),
    'c2': ('24.9k', '4.7', 'BSC040N08NS5'),
    'e': ('24.9k', '6.8', 'BSC040N08NS5'),
    'f': ('24.9k', '10', 'BSC040N08NS5'),
}

def rep(s, old, new, count=1):
    assert s.count(old) == count, (old, s.count(old))
    return s.replace(old, new)

def make(name, var, vin=24, rl=2.4, hot=False, test=0, rfault=0.5, tstop='14m', prime=False,
         temp=None, extra='', overrides=None, state=None):
    rfreq, rgh, q1 = VARIANTS[var] if isinstance(var, str) else var
    o = dict(overrides or {})
    s = BASE
    s = rep(s, 'RsetTop VREF ILIMREF 13k', 'RsetTop VREF ILIMREF ' + o.get('RSETT', '11.8k'))
    s = rep(s, 'R7 N003 0 18.7K', 'R7 N003 0 ' + o.get('ROVB', '17.4k'))
    s = rep(s, 'R3 N004 0 30.1k', 'R3 N004 0 ' + rfreq)
    s = rep(s, 'RgH TG GHI 4.7', 'RgH TG GHI ' + rgh)
    s = rep(s, 'MQ1 QD GH SW BSC026N08NS5', 'MQ1 QD GH SW ' + q1)
    s = rep(s, '.param VIN=24 RL=2.4', f'.param VIN={vin} RL={rl}')
    s = rep(s, '.param TEST=0 RFAULT=.5', f'.param TEST={test} RFAULT={rfault}')
    if 'CSS' in o: s = rep(s, 'C5 N007 0 100n', 'C5 N007 0 ' + o['CSS'])
    if 'COMP' in o: s = rep(s, 'C4 N008 0 22n Rser=10K Cpar=470p', 'C4 N008 0 ' + o['COMP'])
    if hot:
        s = rep(s, 'L1 SW LOUT 33u Rser=20m', 'L1 SW LOUT 33u Rser=24m')
        s = rep(s, 'CinCer IN 0 10u Rser=3m Lser=1n', 'CinCer IN 0 5u Rser=3m Lser=1n')
        s = rep(s, 'Lloop IN QD 5n Rser=2m', 'Lloop IN QD 20n Rser=5m')
        s = rep(s, 'LgH GHI GH 5n Rser=10m', 'LgH GHI GH 20n Rser=25m')
        s = rep(s, 'LgL GLI GL 5n Rser=10m', 'LgL GLI GL 20n Rser=25m')
    for k, v in o.get('replace', []):
        s = rep(s, k, v)
    t = temp if temp is not None else (70 if hot else 27)
    tail = f'.temp {t}\n'
    if prime:
        s = rep(s, 'C5 N007 0 100n', 'C5 N007 0 22n')
        tail += f'.options method=gear\n.tran 0 6m 0 100n\n.savestate "{name}.state"\n'
    else:
        st = state or f'RevF1_{var}_prime{t}.state'
        if o.get('fra'):
            tail += f'.fra loadstate="{st}"\n'
        else:
            if st != 'none':
                tail += f'.loadstate "{st}"\n'
            if o.get('gear'):
                tail += '.options method=gear\n'
            tail += f'.tran 0 {tstop} 0 100n\n'
    s = s.replace('.end', '')  # strip trailing .end then append
    s = s.rstrip() + '\n' + BSC040 + '\n' + extra + '\n* RevF1 generated by gen.py\n' + tail + '.end\n'
    with open(os.path.join(HERE, name + '.cir'), 'w', encoding='latin-1', newline='\r\n') as f:
        f.write(s)
    return name
